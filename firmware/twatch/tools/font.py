#!/usr/bin/env python3
"""Generate compact antialiased Rajdhani ASCII atlases (OFL-1.1)."""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont
p=argparse.ArgumentParser();p.add_argument('font',type=Path);p.add_argument('out',type=Path);a=p.parse_args()
rows=['// Generated by tools/font.py; Rajdhani glyphs: OFL-1.1. See fonts/OFL.txt.', '#pragma once', '#include <cstdint>', 'namespace watchfont {', 'struct Glyph {uint32_t offset; uint8_t width,height,advance; int8_t left,top;};']
for size in (14,20,26,36):
 f=ImageFont.truetype(str(a.font),size);data=[];glyphs=[]
 for code in range(32,127):
  ch=chr(code);l,t,r,b=f.getbbox(ch);w,h=r-l,b-t
  im=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(im).text((-l,-t),ch,font=f,fill=255)
  glyphs.append((len(data),w,h,round(f.getlength(ch)),l,t));data.extend(im.tobytes()[:w*h])
 rows.append('inline constexpr uint8_t pixels%d[]={%s};'%(size,','.join(map(str,data))))
 rows.append('inline constexpr Glyph glyphs%d[]={%s};'%(size,','.join('{'+','.join(map(str,g))+'}' for g in glyphs)))
rows.append('}');a.out.write_text('\n'.join(rows)+'\n')
