/* Scalar canonicalization only; actual point/signature verification belongs to
 * the pinned IDF Mbed TLS wrapper. No hand-written curve operations here. */
#include "p256_native.h"
#include <stddef.h>
static const uint8_t order[32]={
  0xff,0xff,0xff,0xff,0x00,0x00,0x00,0x00,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,
  0xbc,0xe6,0xfa,0xad,0xa7,0x17,0x9e,0x84,0xf3,0xb9,0xca,0xc2,0xfc,0x63,0x25,0x51};
static const uint8_t half_order[32]={
  0x7f,0xff,0xff,0xff,0x80,0x00,0x00,0x00,0x7f,0xff,0xff,0xff,0xff,0xff,0xff,0xff,
  0xde,0x73,0x7d,0x56,0xd3,0x8b,0xcf,0x42,0x79,0xdc,0xe5,0x61,0x7e,0x31,0x92,0xa8};
static int compare(const uint8_t* a,const uint8_t* b){for(size_t i=0;i<32;++i){if(a[i]<b[i])return -1;if(a[i]>b[i])return 1;}return 0;}
static bool nonzero(const uint8_t* p){uint8_t n=0;for(size_t i=0;i<32;++i)n|=p[i];return n!=0;}
bool v12_p256_signature_canonical(const uint8_t signature[64]){
  return signature&&nonzero(signature)&&nonzero(signature+32)&&compare(signature,order)<0&&compare(signature+32,half_order)<=0;
}
