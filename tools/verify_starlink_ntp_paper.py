from pathlib import Path
import argparse,hashlib,importlib.util,json,math

R=Path(__file__).resolve().parents[1];P=R/'papers/starlink-wifi-hybrid-timing'
def compare(a,b,path='result'):
 if isinstance(a,dict):
  assert a.keys()==b.keys(),path
  for k in a:compare(a[k],b[k],path+'.'+k)
 elif isinstance(a,list):
  assert len(a)==len(b),path
  for i,(x,y) in enumerate(zip(a,b)):compare(x,y,path+f'[{i}]')
 elif isinstance(a,(float,int)) and not isinstance(a,bool):assert math.isclose(a,b,rel_tol=1e-9,abs_tol=1e-7),(path,a,b)
 else:assert a==b,(path,a,b)
def hybrid(final=True):
 spec=importlib.util.spec_from_file_location('hybrid_paper',P/'hybrid/analyze.py');h=importlib.util.module_from_spec(spec);spec.loader.exec_module(h)
 result=h.analyze();compare(result,json.loads((P/'hybrid/results.json').read_text()),'hybrid')
 for name,source in h.tables(result).items():assert (P/'hybrid'/name).read_text()==source,name
 provenance=json.loads((P/'hybrid/provenance.json').read_text())
 if final:
  assert provenance['status']=='FIVE_CLOSED_WINDOWS_TWO_FIRMWARE_COHORTS'
  assert list(result['runs'])==['P1','P2','P3','R1','R2']
  assert result['paper_primary_runs']==['R1','R2']
 for run,record in provenance['runs'].items():
  assert record['main_PPS']==record['native_NTP_PPS']==1800 and record['PPS_number_gaps']==record['mismatches']==0
  assert record['all_admitted_method_outputs_deep_verified']==(not result['runs'][run]['independent_replay_limited'])
  if not record['all_admitted_method_outputs_deep_verified']:
   assert record['quality_limit'] and any(v['deep_verified']<v['native_qualified'] for v in record['continuous_qualification_counts'].values())
  assert record['record_identity_checks']['main_selection_same'] and record['record_identity_checks']['future_record_identities_same']
  for method,values in result['runs'][run]['models'].items():
   assert values['nominal']==900 and values['verified_n']+values['unknown_vs_900']==900
   assert values['verified_n']<=values['raw_verified_n']<=values['native_admitted_n']
   if method in record['continuous_qualification_counts']:
    counts=record['continuous_qualification_counts'][method]
    assert values['verified_n']==counts['deep_verified'] and values['raw_verified_n']==counts['raw_prediction_deep_verified']
 return result
def main():
 e=json.loads((P/'edition.json').read_text());assert e['publication_approved'] is False and 1<=e['pages']<=8
 assert e['status']=='AUTHOR_REVIEW_DRAFT'
 approval=json.loads((P/'publication.json').read_text())
 allowed_companions={'papers/README.md','papers/CHANGELOG.md','papers/starlink-wifi-hybrid-timing/README.md','tools/verify_starlink_ntp_paper.py'}
 updates={f['path']:f for f in approval['updated_companions']}
 assert len(updates)==len(approval['updated_companions']) and set(updates)==allowed_companions
 for f in e['files']:
  expected=dict(f)
  if f['path'] in updates:
   u=updates[f['path']];assert f['sha256']==u['prepared_sha256']
   expected.update(bytes=u['current_bytes'],sha256=u['current_sha256'])
  p=R/f['path'];assert p.stat().st_size==expected['bytes'],f['path']
  assert hashlib.sha256(p.read_bytes()).hexdigest()==expected['sha256'],f['path']
 spec=importlib.util.spec_from_file_location('ntp_paper',P/'analyze.py');m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
 result=m.analyze(P);compare(result,json.loads((P/'results.json').read_text()))
 for folder in sorted((P/'controls').iterdir()):
  compare(m.analyze(folder),json.loads((folder/'results.json').read_text()),folder.name)
  audit=json.loads((folder/'observations.json').read_text())['capture_audit']
  assert audit['clean_gate'] and audit['replayed']==audit['qualified']==600
  assert audit['mismatches']==audit['unreplayed']==audit['console_dropped']==0
 table_spec=importlib.util.spec_from_file_location('ntp_tables',P/'make_tables.py');tables=importlib.util.module_from_spec(table_spec);table_spec.loader.exec_module(tables)
 for name,text in tables.products(P).items():
  assert (P/name).read_text()=='% Generated by make_tables.py; CC BY 4.0 Jonathan Yantis.\n'+text,name
 meta=json.loads((P/'observations.json').read_text());audit=meta['capture_audit']
 assert audit['clean_gate'] and audit['replayed']==audit['qualified'] and audit['mismatches']==0
 assert result['counts']['PPS_total']==audit['PPS_rows']
 cohort=json.loads((P/'cohort.json').read_text())
 assert [r['label'] for r in cohort['primary_runs']]==['S1','S2','S3']
 assert cohort['total_distinct_PPS_records']==1800 and cohort['total_distinct_validation_PPS']==900
 for run in cohort['primary_runs']:
  data=json.loads((P/run['folder']/'results.json').read_text())
  compare(run['heldout'],data['heldout'],run['label'])
  compare(run['future_error_trend'],data['future_error_trend'],run['label']+'.trend')
  assert run['capture_audit']['clean_gate'] and data['heldout']['n']==300
 assert cohort['secondary']['shares_validation_witnesses_with']=='S2'
 assert cohort['later_interrupted_trial']['completed_native600s'] is False
 # The prior unapproved beacon manuscript is excluded from this publication.
 # Its provenance hash remains in the immutable prepared edition; it is not a
 # private-file dependency of the public data and manuscript checks.
 excluded=approval['excluded_prior_beacon_study']
 assert excluded['path']=='papers/starlink-wifi-timing/'
 assert excluded['pdf_sha256']==e['prior_beacon_paper_pdf_sha256']
 assert approval['github_push_authorized'] is True
 assert approval['delivery_status']=='AUTHORIZED_FOR_GITHUB_MAIN_PUBLICATION'
 hybrid()
 tex=(P/'starlink-wifi-hybrid-timing.tex').read_text();assert 'Author-review draft' in tex and '\\input{hybrid/' in tex
 assert len(__import__('re').findall(r'^@', (P/'references.bib').read_text(),__import__('re').M))==e['bibliography_entries']
 approval=json.loads((P/'publication.json').read_text())
 assert approval['status']=='APPROVED_FOR_PUBLIC_DRAFT_REVIEW'
 assert approval['draft_promoted_to_final'] is False
 assert approval['reviewed_source_pdf_unchanged'] is True
 assert hashlib.sha256((P/'edition.json').read_bytes()).hexdigest()==approval['edition_sha256']
 for f in approval['publication_files']:
  p=R/f['path'];assert p.stat().st_size==f['bytes'],f['path']
  assert hashlib.sha256(p.read_bytes()).hexdigest()==f['sha256'],f['path']
 pdf=P/'starlink-wifi-hybrid-timing.pdf'
 assert hashlib.sha256(pdf.read_bytes()).hexdigest()==approval['reviewed_pdf_sha256']
 assert hashlib.sha256((P/'starlink-wifi-hybrid-timing.tex').read_bytes()).hexdigest()==approval['reviewed_source_sha256']
 assert (R/'papers/starlink-ntp-frozen-clock/main.pdf').read_bytes()==pdf.read_bytes()
 print('PASS: approved public-review package, unchanged reviewed source/PDF, legacy PDF link, edition hashes and selected-data reproduction')
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--hybrid-only',action='store_true',help='Check current selected hybrid derivatives during preparation, without the final edition manifest')
 args=parser.parse_args()
 if args.hybrid_only:hybrid(final=False);print('PASS: current selected hybrid metrics and tables; not final edition verification')
 else:main()
